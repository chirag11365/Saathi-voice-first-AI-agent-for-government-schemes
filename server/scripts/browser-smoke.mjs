import { chromium } from 'playwright';
import fs from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const consoleErrors=[],pageErrors=[],failedRequests=[];
page.on('console',message=>{if(message.type()==='error')consoleErrors.push(message.text())});
page.on('pageerror',error=>pageErrors.push(error.stack||error.message));
page.on('requestfailed',request=>failedRequests.push({url:request.url(),error:request.failure()?.errorText}));
await page.goto('http://localhost:5173',{waitUntil:'networkidle',timeout:30000}).catch(error=>pageErrors.push(`navigation: ${error.message}`));
await page.locator('.hero h1').waitFor({state:'visible',timeout:10000}).catch(()=>{});
await fs.mkdir('storage',{recursive:true});
await page.screenshot({path:'storage/after-home.png',fullPage:true});
const homeRendered=await page.locator('.hero h1').isVisible().catch(()=>false);
await page.locator('select.language').selectOption('hi').catch(()=>{});
await page.waitForFunction(()=>Boolean(sessionStorage.getItem('saathi-session'))).catch(()=>{});
await page.getByRole('button',{name:/Farmer/}).click().catch(()=>{});
await page.waitForFunction(()=>document.querySelector('.profile')?.innerText.toLowerCase().includes('farmer'),{timeout:45000}).catch(error=>pageErrors.push(`Hindi farmer profile: ${error.message}`));
const farmerProfile=(await page.locator('.profile').innerText().catch(()=>''));
await page.screenshot({path:'storage/after-farmer-chat.png',fullPage:true});
await page.getByRole('link',{name:'Schemes'}).click().catch(()=>{});
await page.locator('.scheme-card h2').first().waitFor({state:'visible',timeout:45000}).catch(error=>pageErrors.push(`scheme matches: ${error.message}`));
await page.screenshot({path:'storage/after-farmer-matches.png',fullPage:true});
const pmKisan=await page.locator('.scheme-card').filter({hasText:'पीएम-किसान'}).innerText().catch(()=>'' )||await page.locator('.scheme-card').filter({hasText:'PM-KISAN'}).innerText().catch(()=>'' );
console.log(JSON.stringify({title:await page.title(),homeRendered,farmerProfile,pmKisan:pmKisan.slice(0,500),consoleErrors,pageErrors,failedRequests},null,2));
await browser.close();
